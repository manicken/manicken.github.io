#!/usr/bin/env node
// fpbc: compile a Faust FBC file (faust -lang interp x.dsp -o x.fbc) to an FPB container.
//
//   node fpb/tools/fpbc.js <in.fbc> [-o out.fpb] [--header out.h] [--name symbol] [--sr 44117] [--ops FPB_oplist.h]
//
// --header writes a C header with the container as a PROGMEM byte array and the parameters as comments,
// ready for AudioEffectFPB::load() in a sketch.
"use strict";
const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..", "..");
global.RED = {};
["fpb-core", "fpb-fbc", "fpb-format", "fpb-vm", "fpb-compile-fbc"].forEach(f => require(path.join(ROOT, "red", "fpb", f + ".js")));

const argv = process.argv.slice(2);
function opt(name, def) { const i = argv.indexOf(name); return i >= 0 ? argv[i + 1] : def; }
const input = argv.find((a, i) => !a.startsWith("-") && !(i > 0 && argv[i - 1].startsWith("-")));
if (!input) {
    console.log("usage: node fpb/tools/fpbc.js <in.fbc> [-o out.fpb] [--header out.h] [--name symbol] [--sr 44117] [--ops FPB_oplist.h]");
    process.exit(1);
}
const base = path.basename(input).replace(/\.fbc$/, "");
const out = opt("-o", input.replace(/\.fbc$/, "") + ".fpb");
const headerOut = opt("--header", null);
const symbol = opt("--name", base.replace(/\W/g, "_") + "_fpb");
const sr = parseInt(opt("--sr", "44117"), 10);
const opsFile = opt("--ops", path.join(ROOT, "fpb", "teensy", "FPB", "src", "FPB_oplist.h"));

function num(v) { return String(+(+v).toPrecision(7)); }   // float32 values without the double noise
const table = RED.fpb.core.parseOpList(fs.readFileSync(opsFile, "utf8"));
const model = RED.fpb.fbc.parse(fs.readFileSync(input, "utf8"));
const res = RED.fpb.compileFBC(model, table, { sampleRate: sr });

// verify before writing: the container must load and match the FBC reference
const vm = RED.fpb.vm.load(res.bytes, table);
if (vm.error) { console.error("verify: the container does not load: " + vm.errorName); process.exit(2); }
{
    const ref = new RED.fpb.fbc.Interp(model);
    ref.init(sr);
    const N = 128, ins = [], o1 = [], o2 = [];
    for (let c = 0; c < model.inputs; c++) ins.push(new Float32Array(N).map((_, k) => Math.sin(k * 0.3 + c) * 0.5));
    for (let c = 0; c < model.outputs; c++) { o1.push(new Float32Array(N)); o2.push(new Float32Array(N)); }
    let max = 0;
    for (let b = 0; b < 16; b++) {
        ref.compute(N, ins, o1);
        vm.process(ins, o2, N);
        for (let c = 0; c < model.outputs; c++) for (let k = 0; k < N; k++) max = Math.max(max, Math.abs(o1[c][k] - o2[c][k]));
    }
    if (max > 1e-6) { console.error("verify: output differs from the FBC reference by " + max); process.exit(3); }
}

fs.writeFileSync(out, res.bytes);
const st = res.stats;
console.log(`${input} -> ${out} (${st.bytes} bytes)`);
console.log(`  inputs ${model.inputs}, outputs ${model.outputs}, sample rate ${sr}`);
console.log(`  per sample: FBC ${st.fbcSample} -> FPB ${st.smp} instructions; per block: FBC ${st.fbcControl} -> FPB ${st.blk}`);
st.arrays.forEach((a, i) => console.log(`  array ${i}: ${a.len} x ${a.type === "f" ? "float" : "int"} (${a.len * 4} bytes, tier ${a.tier})`));
res.params.forEach(p => console.log(`  param ${p.index}: ${p.path}  ${p.min}..${p.max} step ${p.step}  default ${num(p.def)}` +
    (Object.keys(p.meta).length ? "  " + JSON.stringify(p.meta) : "")));
res.warnings.forEach(w => console.log("  warning: " + w));

if (headerOut) {
    const lines = [];
    lines.push(`// ${path.basename(headerOut)}: generated by fpb/tools/fpbc.js from ${path.basename(input)}`);
    lines.push(`// inputs ${model.inputs}, outputs ${model.outputs}, sample rate ${sr}, ${st.bytes} bytes`);
    lines.push(`// FPB instructions: ${st.blk} per block, ${st.smp} per sample`);
    lines.push("// parameters (index for AudioEffectFPB::setParam):");
    res.params.forEach(p => lines.push(`//   ${p.index}: ${p.path}  ${p.min}..${p.max}  default ${num(p.def)}` +
        (p.meta.unit ? " " + p.meta.unit : "") + (p.meta.scale ? " (" + p.meta.scale + ")" : "")));
    lines.push("#pragma once");
    lines.push("#include <stdint.h>");
    lines.push("#ifndef PROGMEM");
    lines.push("#define PROGMEM");
    lines.push("#endif");
    res.params.forEach(p => lines.push(`#define ${symbol.toUpperCase()}_${p.path.replace(/\W/g, "_").toUpperCase()} ${p.index}`));
    lines.push(`static const uint8_t ${symbol}[${st.bytes}] PROGMEM = {`);
    for (let i = 0; i < res.bytes.length; i += 16) {
        lines.push("    " + Array.from(res.bytes.subarray(i, i + 16)).map(b => "0x" + b.toString(16).padStart(2, "0")).join(",") + ",");
    }
    lines.push("};");
    fs.writeFileSync(headerOut, lines.join("\n") + "\n");
    console.log(`  header ${headerOut} (symbol ${symbol})`);
}
